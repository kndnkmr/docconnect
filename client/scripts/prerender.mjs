// ---- Apply a route's meta to the template HTML ----
// We replace only the specific known static strings from index.html. If any of
// these anchor strings ever changes in index.html, the matching replace becomes
// a no-op — so we assert each critical replacement actually happened, failing
// the build loudly rather than silently shipping wrong/stale meta.
function applyMeta(template, route) {
  const title = fullTitle(route.title);
  const desc = route.description || '';
  const url = `${SITE}${route.path}`;
  const eTitle = esc(title);
  const eDesc = esc(desc);
  const eUrl = esc(url);

  let html = template;
  const checks = [];
  const replaceOnce = (find, replace, label) => {
    if (!html.includes(find)) { checks.push(label); return; }
    html = html.replace(find, replace);
  };

  // <title>
  replaceOnce(
    '<title>ProMedicoz - Find & Book Doctors Online | India</title>',
    `<title>${eTitle}</title>`,
    'title'
  );
  // <meta name="description">
  replaceOnce(
    '<meta name="description" content="ProMedicoz - India\'s doctor consultation platform. Find qualified doctors, book appointments online, video consultations, and manage your health." />',
    `<meta name="description" content="${eDesc}" />`,
    'description'
  );
  // og:title
  replaceOnce(
    '<meta property="og:title" content="ProMedicoz - Consult Verified Doctors Online" />',
    `<meta property="og:title" content="${eTitle}" />`,
    'og:title'
  );
  // og:description
  replaceOnce(
    '<meta property="og:description" content="Find and book verified doctors across India — video, phone, or in-person. Book in under 2 minutes. Your health, our priority." />',
    `<meta property="og:description" content="${eDesc}" />`,
    'og:description'
  );
  // og:url
  replaceOnce(
    '<meta property="og:url" content="https://www.promedicoz.in/" />',
    `<meta property="og:url" content="${eUrl}" />`,
    'og:url'
  );
  // og:image + twitter:image — only when this route has a specific share card
  // (blog articles + specialization pages). Other routes keep the default
  // banner. We replace the default URL everywhere it appears (both the og and
  // twitter image tags point at the same default), so a single value swap on
  // each is enough. Not asserted as "missing" when there's no card: that's the
  // intended no-op for pages that use the default image.
  if (route.ogImage) {
    const eImg = esc(route.ogImage);
    html = html.replace(
      '<meta property="og:image" content="https://www.promedicoz.in/og-image.png" />',
      `<meta property="og:image" content="${eImg}" />`
    );
    html = html.replace(
      '<meta name="twitter:image" content="https://www.promedicoz.in/og-image.png" />',
      `<meta name="twitter:image" content="${eImg}" />`
    );
  }
  // og:type
  replaceOnce(
    '<meta property="og:type" content="website" />',
    `<meta property="og:type" content="${esc(route.type || 'website')}" />`,
    'og:type'
  );
  // twitter:title
  replaceOnce(
    '<meta name="twitter:title" content="ProMedicoz - Consult Verified Doctors Online" />',
    `<meta name="twitter:title" content="${eTitle}" />`,
    'twitter:title'
  );
  // twitter:description
  replaceOnce(
    '<meta name="twitter:description" content="Find and book verified doctors across India — video, phone, or in-person. Book in under 2 minutes." />',
    `<meta name="twitter:description" content="${eDesc}" />`,
    'twitter:description'
  );

  // Crawler-readable body copy, inside #root but `hidden` (never shown to
  // users; React replaces #root's contents on mount). See blocksToHtml notes.
  if (route.bodyHtml) {
    replaceOnce(
      '<div id="root"></div>',
      `<div id="root"><div data-prerender="seo" hidden>\n${route.bodyHtml}\n</div></div>`,
      'root'
    );
  }

  // Page-specific structured data (Article / Breadcrumb / Physician).
  if (Array.isArray(route.jsonLd) && route.jsonLd.length) {
    html = html.replace('</head>', `    ${route.jsonLd.map(jsonLdTag).join('\n    ')}\n  </head>`);
  }

  // Inject a canonical link (index.html has none in the static head). We add it
  // right before the closing </head> so it's always present in raw HTML.
  const canonicalTag = `<link rel="canonical" href="${eUrl}" />`;
  if (!html.includes('rel="canonical"')) {
    html = html.replace('</head>', `    ${canonicalTag}\n  </head>`);
  }

  return { html, missing: checks };
}

// ---- Generate sitemap.xml from the SAME route list we prerender ----
// WHY: the sitemap must never drift from the actual set of indexable pages.
// Because buildRoutes() is the single source of truth for what we prerender,
// deriving the sitemap from it guarantees every new blog article (and page)
// appears in the sitemap automatically on the next build — no manual edits.
// We deliberately mirror the same routes that get prerendered/indexed and skip
// the noindex utility/auth routes (which are not in `routes` at all).
function priorityFor(route) {
  if (route.path === '/') return { priority: '1.0', changefreq: 'weekly' };
  if (route.path === '/doctors') return { priority: '0.9', changefreq: 'daily' };
  if (route.path === '/blog') return { priority: '0.8', changefreq: 'weekly' };
  if (route.path.startsWith('/specialization/')) return { priority: '0.8', changefreq: 'weekly' };
  if (route.path.startsWith('/blog/')) return { priority: '0.7', changefreq: 'monthly' };
  if (route.path.startsWith('/dr/')) return { priority: '0.6', changefreq: 'weekly' };
  // Other static pages (about, how-it-works, legal, etc.)
  return { priority: '0.5', changefreq: 'monthly' };
}

async function writeSitemap(routes) {
  const today = new Date().toISOString().slice(0, 10); // YYYY-MM-DD
  const body = routes
    .map((route) => {
      const { priority, changefreq } = priorityFor(route);
      return [
        '  <url>',
        `    <loc>${esc(SITE + route.path)}</loc>`,
        `    <lastmod>${today}</lastmod>`,
        `    <changefreq>${changefreq}</changefreq>`,
        `    <priority>${priority}</priority>`,
        '  </url>',
      ].join('\n');
    })
    .join('\n');
  const xml = `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n${body}\n</urlset>\n`;
  await writeFile(join(DIST, 'sitemap.xml'), xml, 'utf8');
  return routes.length;
}

async function main() {
  if (!existsSync(TEMPLATE_PATH)) {
    console.error(`[prerender] dist/index.html not found at ${TEMPLATE_PATH}. Run "vite build" first.`);
    process.exit(1);
  }

  const template = await readFile(TEMPLATE_PATH, 'utf8');
  const routes = await buildRoutes();

  let written = 0;
  const missingByRoute = [];

  for (const route of routes) {
    const { html, missing } = applyMeta(template, route);
    if (missing.length) missingByRoute.push({ path: route.path, missing });

    if (route.path === '/') {
      // Home: overwrite dist/index.html in place.
      await writeFile(TEMPLATE_PATH, html, 'utf8');
    } else {
      // Others: dist/<route>/index.html (directory-style URL).
      const outDir = join(DIST, route.path.replace(/^\//, ''));
      await mkdir(outDir, { recursive: true });
      await writeFile(join(outDir, 'index.html'), html, 'utf8');
    }
    written++;
  }

  // If the template's anchor strings didn't match (index.html changed), fail
  // loudly — we must not silently ship pages with stale/wrong meta.
  if (missingByRoute.length) {
    console.error('[prerender] ERROR: some meta anchors were not found in dist/index.html.');
    console.error('[prerender] This usually means index.html <head> changed and the script needs updating.');
    for (const m of missingByRoute.slice(0, 3)) {
      console.error(`  - ${m.path}: missing [${m.missing.join(', ')}]`);
    }
    process.exit(1);
  }

  // Regenerate sitemap.xml from the same route list, so it always matches the
  // pages we actually ship (Vite already copied public/sitemap.xml into dist;
  // this overwrites it with the up-to-date one).
  const sitemapCount = await writeSitemap(routes.filter((r) => !r.noSitemap));

  console.log(`[prerender] Wrote ${written} prerendered routes (static pages + ${routes.filter(r => r.path.startsWith('/blog/')).length} articles + specializations).`);
  console.log(`[prerender] Wrote dist/sitemap.xml with ${sitemapCount} URLs.`);
}

main().catch((err) => {
  console.error('[prerender] Failed:', err);
  process.exit(1);
});
